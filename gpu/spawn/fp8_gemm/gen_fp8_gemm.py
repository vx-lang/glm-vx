#!/usr/bin/env python3
"""Write the FP8 GEMM's generated Vx sources (glm-vx #10). Run from anywhere; rerun after editing
fp8_gemm.vx.in or VARIANTS, and commit the outputs (build.sh does not run this).

- wgmma_m64n128k32.vx: a device function whose mlir! block issues one 128-k block of
  wgmma.mma_async.m64n128k32.f32.e4m3.e4m3 (four k32 steps) on a 64-f32 REG tensor.
- fp8_gemm_<name>.vx: the kernel (fp8_gemm.vx.in) for each variant in VARIANTS, with its tile and
  ring constants filled in.

`python3 gen_fp8_gemm.py --check` exits 1 if a committed output differs from what it would write.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

# consumers: warpgroups of 64 rows each (BLOCK_M = 64 * consumers); stages: shared ring depth.
VARIANTS = {
    'm64': {'consumers': 1, 'stages': 4},
    'm128': {'consumers': 2, 'stages': 4},
}
BLOCK_N = 128
BLOCK_K = 128          # bytes of k per stage = one 128-byte swizzle row = one scale block
ACC = BLOCK_N // 2     # f32 accumulator registers per thread for m64nNk32: N / 2


def wgmma_function(name='wgmma_m64n128k32_k128', n=BLOCK_N, steps=BLOCK_K // 32):
    """One K block: `steps` wgmma k32 steps, the first with scale-d 0 (D = A B), the others D += A B.

    With 128-byte swizzle and K-major tiles, step s starts 32 * s bytes into each 128-byte row:
    the descriptors' start address field goes up by 2 (32 >> 4) a step, as CUTLASS's
    DescriptorIterator and DeepGEMM advance it. The swizzle is applied by the hardware to the
    address it computes, so the same XOR pattern that TMA wrote is undone (PTX ISA 9.7.15.5.1).
    """
    regs = n // 2
    st = '!llvm.struct<(' + ', '.join(['f32'] * regs) + ')>'
    ft = ', '.join(['f32'] * regs)
    outs = ','.join(['=f'] * regs)
    ties = ','.join(str(i) for i in range(regs))
    dlist = ', '.join(f'${i}' for i in range(regs))
    lines = [
        f'// Generated by gen_fp8_gemm.py: one 128-k block of wgmma.mma_async.m64n{n}k32.f32.e4m3.e4m3 on a',
        f'// {regs}-f32 REG tensor (PTX ISA 9.7.15.5.2: register i is row 16 * warp + lane / 4 + 8 * ((i >> 1) & 1),',
        '// column 8 * (i >> 2) + 2 * (lane % 4) + (i & 1)). a_desc and b_desc address the stage\'s tiles; step s',
        '// adds 2 (32 bytes) to both. Step 0 has scale-d 0, so acc = A_kb B_kb^T of this block alone. The',
        '// block ends with commit_group and wait_group 0, so acc is final and the stage is no longer read.',
        f'fn {name}(acc: &mut Tensor<f32, [{regs}], Memory::REG>, a_desc: i64, b_desc: i64) on Topology::Device -> i32 {{',
        f'  return mlir!( inputs : (%acc = acc : memref<{regs}xf32>, %ad = a_desc : i64, %bd = b_desc : i64), returns : i32,',
        '                dialects : ["llvm", "memref", "arith"]) {',
    ]
    lines += [f'    %i{i} = arith.constant {i} : index' for i in range(regs)]
    lines += [f'    %c{i} = memref.load %acc[%i{i}] : memref<{regs}xf32>' for i in range(regs)]

    def tied(prefix):
        return ', '.join(f'%{prefix}{i}' for i in range(regs))
    # wgmma.fence (9.7.15.7.1): orders this warpgroup's register writes of acc (the promotion of
    # the previous block read it) before wgmma reads or writes it.
    lines.append(f'    %f = llvm.inline_asm has_side_effects "wgmma.fence.sync.aligned;", "{outs},{ties}" {tied("c")} : ({ft}) -> {st}')
    lines += [f'    %f{i} = llvm.extractvalue %f[{i}] : {st}' for i in range(regs)]
    prev = 'f'
    for s in range(steps):
        lines.append(f'    %off{s} = arith.constant {2 * s} : i64')
        lines.append(f'    %ad{s} = arith.addi %ad, %off{s} : i64')
        lines.append(f'    %bd{s} = arith.addi %bd, %off{s} : i64')
        lines.append(f'    %sd{s} = arith.constant {0 if s == 0 else 1} : i32')
        asm = (f'{{ .reg .pred p; setp.ne.b32 p, ${regs + 2}, 0; wgmma.mma_async.sync.aligned.m64n{n}k32.f32.e4m3.e4m3 '
               f'{{{dlist}}}, ${regs}, ${regs + 1}, p, 1, 1; }}')
        lines.append(f'    %w{s} = llvm.inline_asm has_side_effects "{asm}", "{outs},l,l,r,{ties}" '
                     f'%ad{s}, %bd{s}, %sd{s}, {tied(prev)} : (i64, i64, i32, {ft}) -> {st}')
        lines += [f'    %w{s}_{i} = llvm.extractvalue %w{s}[{i}] : {st}' for i in range(regs)]
        prev = f'w{s}_'
    # commit_group + wait_group 0 (9.7.15.7.2-3), with acc passed through so nothing reads it early.
    lines.append(f'    %d = llvm.inline_asm has_side_effects "wgmma.commit_group.sync.aligned; wgmma.wait_group.sync.aligned 0;", '
                 f'"{outs},{ties}" {tied(prev)} : ({ft}) -> {st}')
    for i in range(regs):
        lines.append(f'    %d{i} = llvm.extractvalue %d[{i}] : {st}')
        lines.append(f'    memref.store %d{i}, %acc[%i{i}] : memref<{regs}xf32>')
    lines += ['    %z = arith.constant 0 : i32', '    macro.yield %z : i32', '  };', '}', '']
    return '\n'.join(lines)


def constants(name, consumers, stages):
    block_m = 64 * consumers
    a_stage = block_m * BLOCK_K        # bytes of A per stage
    b_stage = BLOCK_N * BLOCK_K
    return {
        'NAME': name, 'CONSUMERS': consumers, 'STAGES': stages, 'BLOCK_M': block_m, 'BLOCK_N': BLOCK_N,
        'ACC': ACC, 'A_STAGE': a_stage, 'B_STAGE': b_stage, 'A_STAGE_DESC': a_stage // 16, 'B_STAGE_DESC': b_stage // 16,
        'RING_A_WORDS': stages * a_stage // 4, 'RING_B_WORDS': stages * b_stage // 4, 'BARS': 2 * stages,
        'TX_BYTES': a_stage + b_stage, 'PRODUCER': 128 * consumers, 'THREADS': 128 * consumers + 32,
        'EMPTY_ARRIVALS': 4 * consumers,
        'SHARED_BYTES': stages * (a_stage + b_stage) + 16 * stages,
    }


def kernel(name, consumers, stages):
    text = (HERE / 'fp8_gemm.vx.in').read_text()
    for key, value in constants(name, consumers, stages).items():
        text = text.replace(f'@{key}@', str(value))
    if '@' in text.replace('@@', ''):
        raise SystemExit(f'unfilled placeholder in fp8_gemm.vx.in: {text[text.index("@"):][:40]!r}')
    return f'// Generated by gen_fp8_gemm.py from fp8_gemm.vx.in ({name}: {consumers} consumer warpgroup(s), {stages} stages).\n' + text


def outputs():
    files = {'wgmma_m64n128k32.vx': wgmma_function()}
    for name, v in VARIANTS.items():
        files[f'fp8_gemm_{name}.vx'] = kernel(name, v['consumers'], v['stages'])
    return files


def main(argv):
    stale = []
    for filename, text in outputs().items():
        path = HERE / filename
        if '--check' in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(filename)
        else:
            path.write_text(text)
    if stale:
        print('stale generated files: ' + ', '.join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
