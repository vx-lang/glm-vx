"""Writes topk_select_ilp_hist_at.vx from topk_select_ilp_at.vx (#32): the same kernel without its first
pass. The scores kernels index_scores_mma_hist_at and index_scores_fp8_hist_at (gen_index_mma.py) count
the keys' top 12 bits into hist[4096] as they write the scores; this kernel reads that histogram in place
of its own pass A, so it reads the scores twice, not three times, and then zeroes hist for the next
layer's scores (whatever tokens is, so a step with tokens <= k leaves it zero too).

`python3 gen_topk_hist.py --check` exits 1 if the committed output differs (build.sh runs it).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def replace_once(text, old, new):
    assert text.count(old) == 1, old[:80]
    return text.replace(old, new)


def source():
    text = (HERE / 'topk_select_ilp_at.vx').read_text()
    head, body = text.split('// spawn-include: ../device.vx\n', 1)
    head = ('// Generated by gen_topk_hist.py from topk_select_ilp_at.vx: that kernel with its pass A (the keys\'\n'
            '// top 12 bits\' histogram) read from hist[4096], which index_scores_mma_hist_at or\n'
            '// index_scores_fp8_hist_at counted as it wrote the scores; this kernel zeroes it at the end.\n//\n'
            + head)
    body = replace_once(body,
                        'pub fn glm_vx_spawn_topk_select_ilp_at(out_ids: &Tensor<i32, [?], Memory::HBM>, '
                        'scores: &Tensor<i32, [?], Memory::HBM>,\n',
                        'pub fn glm_vx_spawn_topk_select_ilp_hist_at(out_ids: &Tensor<i32, [?], Memory::HBM>, '
                        'scores: &Tensor<i32, [?], Memory::HBM>,\n'
                        '                                            hist: &mut Tensor<u32, [?], Memory::HBM>,\n')
    body = replace_once(body, '                                       step: &Tensor<i32, [?], Memory::HBM>, k: i32) -> void {\n',
                        '                                            step: &Tensor<i32, [?], Memory::HBM>, k: i32) -> void {\n')
    body = replace_once(body, '        let hist = Tensor<u32, [4096], Memory::SMEM>::fill(0u32);\n', '')
    start = body.index("        // A: the top 12 bits' histogram.\n")
    end = body.index('        // B = the largest bin d with above[d] >= need')
    body = body[:start] + body[end:]
    # Zero hist after its last read, whatever tokens is.
    tail = '      }\n    }\n  }\n  return;\n}\n'
    assert body.endswith(tail)
    body = body[:-len(tail)] + ('      }\n'
                                '      // hist back to zero for the next layer\'s scores kernel.\n'
                                '      for l in 0..1024 across lanes {\n'
                                '        for j in 0..4 { hist[4 * l + j] = 0u32; }\n'
                                '      }\n'
                                '    }\n  }\n  return;\n}\n')
    return head + '// spawn-include: ../device.vx\n' + body


def common():
    """topk_select_ilp_at.vx's macros and warp helpers, for the multi-block kernels (topk_mb_*_at.vx) to
    include: the key map, count_lanes, count_lanes_below, the warp sums, sort_bin! and place!."""
    text = (HERE / 'topk_select_ilp_at.vx').read_text()
    helpers = text[text.index('import core::sync::atomic;\n'):text.index('pub fn glm_vx_spawn_topk_select_ilp_at')]
    return ('// Generated by gen_topk_hist.py: topk_select_ilp_at.vx\'s macros and warp helpers (warp instructions in\n'
            '// mlir! blocks), included by the multi-block top-k kernels topk_mb_list_at and topk_mb_write_at.\n'
            + helpers.rstrip() + '\n')


def main():
    outputs = {'topk_select_ilp_hist_at.vx': source(), 'topk_common.vx': common()}
    stale = [n for n, t in outputs.items() if not (HERE / n).exists() or (HERE / n).read_text() != t]
    if '--check' in sys.argv:
        if stale:
            print(f'{", ".join(stale)}: not what gen_topk_hist.py writes; rerun it', file=sys.stderr)
            sys.exit(1)
        return
    for name, text in outputs.items():
        (HERE / name).write_text(text)


if __name__ == '__main__':
    main()
