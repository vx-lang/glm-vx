"""Writes topk_select_bitmap_stats_at.vx from topk_select_bitmap_at.vx (#63): the same kernel with one more
tensor, stats[4], that each launch with tokens > k adds to. It is for measuring, not for serving:
ResidentGLM(topk_bitmap='stats') launches it, and stats says how often the threshold bin held more than
2048 keys, so that the two rounds read the scores again.

  stats[0]  launches with tokens > k
  stats[1]  of them, launches whose threshold bin held more than 2048 keys
  stats[2]  the most keys the threshold bin held
  stats[3]  of them, launches whose threshold bin held more than 1024 keys (half the list)

`python3 gen_topk_bitmap_stats.py --check` exits 1 if the committed output differs (build.sh runs it).
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def replace_once(text, old, new):
    assert text.count(old) == 1, old[:80]
    return text.replace(old, new)


def source():
    text = (HERE / 'topk_select_bitmap_at.vx').read_text()
    text = ('// Generated by gen_topk_bitmap_stats.py from topk_select_bitmap_at.vx: that kernel with stats[4], which\n'
            '// each launch with tokens > k adds to: launches, launches whose threshold bin held more than 2048 keys,\n'
            '// the most keys it held, and launches whose bin held more than 1024.\n//\n' + text)
    text = replace_once(text, 'pub extern fn glm_vx_spawn_topk_select_bitmap_at(', 'pub extern fn glm_vx_spawn_topk_select_bitmap_stats_at(')
    text = replace_once(text, '                                                 hist: &mut Tensor<u32, [?], Memory::HBM>,\n',
                        '                                                       hist: &mut Tensor<u32, [?], Memory::HBM>,\n'
                        '                                                       stats: &mut Tensor<u32, [?], Memory::HBM>,\n')
    text = replace_once(text, '''pub extern fn glm_vx_spawn_topk_select_bitmap_stats_at(out_ids: &mut Tensor<i32, [?], Memory::HBM>, scores: &Tensor<i32, [?], Memory::HBM>,
''', '''pub extern fn glm_vx_spawn_topk_select_bitmap_stats_at(out_ids: &mut Tensor<i32, [?], Memory::HBM>,
                                                       scores: &Tensor<i32, [?], Memory::HBM>,
''')
    text = replace_once(text, '                                                 step: &Tensor<i32, [?], Memory::HBM>, k: i32) -> void {\n',
                        '                                                       step: &Tensor<i32, [?], Memory::HBM>, k: i32) -> void {\n')
    text = replace_once(text, '''            let listed: bool = sel[7] != 0u32;
            for j in 0..4 { hist[4 * (32 * g + t) + j] = 0u32; }
''', '''            let listed: bool = sel[7] != 0u32;
            for j in 0..4 { hist[4 * (32 * g + t) + j] = 0u32; }
            if g == 0 && t == 0 {
              stats[0] = stats[0] + 1u32;
              if !listed { stats[1] = stats[1] + 1u32; }
              stats[2] = stats[2].max(sel[6]);
              if sel[6] > 1024u32 { stats[3] = stats[3] + 1u32; }
            }
''')
    return text


def main():
    path = HERE / 'topk_select_bitmap_stats_at.vx'
    text = source()
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != text:
            print(f'{path.name}: not what gen_topk_bitmap_stats.py writes; rerun it', file=sys.stderr)
            sys.exit(1)
        return
    path.write_text(text)


if __name__ == '__main__':
    main()
